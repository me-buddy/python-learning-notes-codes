# ======================= K-Means Algorithm =======================================
# It is an unsupervised learning algorithm that groups similar data on the basis of 
# their centroid.

# Here’s a synthetic dataset for clustering in unsupervised learning using Python. It contains 500 data points with 4 natural clusters, suitable for K-Means, DBSCAN, and Hierarchical Clustering.

## 1. Generate the dataset



import pandas as pd
from sklearn.datasets import make_blobs
import matplotlib.pyplot as plt
import seaborn as sns

from sklearn.cluster import kmeans

# Generate synthetic data for clustering
X, _ = make_blobs(
    n_samples=500,
    centers=4,
    n_features=2,
    cluster_std=1.2,
    random_state=42
)

# Create a DataFrame without cluster labels
df = pd.DataFrame(X, columns=["Feature_1", "Feature_2"])

# Save the dataset
df.to_csv("clustering_dataset.csv", index=False)

# Display first 5 rows
print(df.head())
print("\nDataset shape:", df.shape)

# Visualize the unlabeled dataset
plt.scatter(df["Feature_1"], df["Feature_2"], s=30)
plt.xlabel("Feature_1")
plt.ylabel("Feature_2")
plt.title("Synthetic Dataset for Unsupervised Clustering")
plt.show()


