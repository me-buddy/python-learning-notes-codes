# 4. Apply K-Means clustering

# After generating the dataset, run this code to discover the clusters:


from sklearn.cluster import KMeans
import matplotlib.pyplot as plt

from sklearn.preprocessing import StandardScaler
from sklearn.metrics import silhouette_score


kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)

# Discover cluster assignments
df["Cluster"] = kmeans.fit_predict(
    df[["Feature_1", "Feature_2"]]
)

# Visualize the discovered clusters
plt.scatter(
    df["Feature_1"],
    df["Feature_2"],
    c=df["Cluster"],
    cmap="viridis",
    s=30
)

plt.scatter(
    kmeans.cluster_centers_[:, 0],
    kmeans.cluster_centers_[:, 1],
    marker="X",
    s=200,
    c="red",
    label="Centroids"
)

plt.xlabel("Feature_1")
plt.ylabel("Feature_2")
plt.title("K-Means Clustering Results")
plt.legend()
plt.show()

df.to_csv("clustered_dataset.csv", index=False)


# Note: K-Means assigns cluster IDs after learning from the features. Those IDs are not original labels, so the dataset remains suitable for demonstrating unsupervised learning.
